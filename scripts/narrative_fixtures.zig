//! Convert pinned Valhalla narrative test inputs and reference strings to Zig.
const std = @import("std");
const cpp = @import("narrative_cpp.zig");
const io = @import("io");
const Allocator = std.mem.Allocator;
const Writer = io.Writer;

pub fn main(init: std.process.Init) !void {
    var args = std.process.Args.Iterator.init(init.minimal.args);
    _ = args.skip();
    const root = args.next() orelse return error.MissingValhallaCheckout;
    const output_path = args.next() orelse return error.MissingOutputPath;
    const check = if (args.next()) |option| blk: {
        if (!eq(option, "--check") or args.next() != null) return error.InvalidOption;
        break :blk true;
    } else false;

    const a = init.arena.allocator();
    const source = try readTest(a, root, "narrativebuilder.cc");
    const maneuvers = try readTest(a, root, "maneuversbuilder.cc");
    const sign_tests = try readTest(a, root, "signs.cc");
    const dictionary_tests = try readTest(a, root, "narrative_dictionary.cc");
    const result = try generate(a, source, maneuvers, sign_tests, dictionary_tests);
    const sentinel = try a.dupeSentinel(u8, result, 0);
    var ast = try std.zig.Ast.parse(a, sentinel, .{});
    defer ast.deinit(a);
    if (ast.errors.len != 0) return error.InvalidGeneratedSource;
    const formatted = try ast.renderAlloc(a);
    if (check) {
        const existing = try io.readFileAlloc(a, output_path, 2 * 1024 * 1024);
        if (!eq(existing, formatted)) return error.SnapshotFixturesOutOfDate;
    } else {
        try io.writeFile(output_path, formatted);
    }
}

fn readTest(a: Allocator, root: []const u8, name: []const u8) ![]const u8 {
    const path = try std.fs.path.join(a, &.{ root, "test", name });
    return io.readFileAlloc(a, path, 2 * 1024 * 1024);
}

const Test = struct { name: []const u8, body: []const u8 };

fn nextTest(a: Allocator, scanner: *cpp.Scanner, suite: []const u8) !?Test {
    while (try cpp.nextCall(scanner, "TEST", false)) |call| {
        const args = try cpp.arguments(a, call.arguments);
        if (args.len != 2) return error.InvalidTestDeclaration;
        const start = (try scanner.next()) orelse return error.ExpectedTestBody;
        if (!start.is("{")) return error.ExpectedTestBody;
        const body = try scanner.group(start);
        if (eq(args[0], suite)) return .{ .name = args[1], .body = body };
    }
    return null;
}

fn generate(a: Allocator, source: []const u8, maneuvers: []const u8, sign_tests: []const u8, dictionary_tests: []const u8) ![]const u8 {
    var result = Writer.Allocating.init(a);
    errdefer result.deinit();
    const out = &result.writer;
    try out.writeAll(
        \\// Ported from test/narrativebuilder.cc (Valhalla 3.9.3).
        \\// Generated by zig build narrative-fixtures.
        \\const trip = @import("../api/trip.zig");
        \\const request = @import("../api/request.zig");
        \\const Maneuver = @import("maneuver.zig").Maneuver;
        \\
        \\pub const Speech = struct { succinct: []const u8 = "", alert: []const u8 = "", pre: []const u8 = "", post: []const u8 = "" };
        \\pub const Step = struct { maneuver: Maneuver, text: []const u8, speech: Speech = .{} };
        \\pub const Case = struct {
        \\    name: []const u8,
        \\    language: []const u8 = "en-US",
        \\    units: request.Units = .miles,
        \\    upstream_disabled: bool = false,
        \\    destination: trip.Location = .{},
        \\    steps: []const Step,
        \\};
        \\
        \\pub const visual = [_]Case{
        \\
    );
    var scanner: cpp.Scanner = .{ .source = source };
    var build_count: usize = 0;
    var all_count: usize = 0;
    var transit: std.ArrayList([]const u8) = .empty;
    var direct: std.ArrayList(Test) = .empty;
    while (try nextTest(a, &scanner, "NarrativeBuilder")) |fixture| {
        all_count += 1;
        if (std.mem.startsWith(u8, fixture.name, "TestBuildTransit")) {
            try transit.append(a, fixture.name);
        } else if (std.mem.startsWith(u8, fixture.name, "TestBuild") or std.mem.startsWith(u8, fixture.name, "DISABLED_TestBuild")) {
            writeBuildCase(a, out, source, fixture) catch |err| {
                std.debug.print("{s}: {s}\n", .{ fixture.name, @errorName(err) });
                return err;
            };
            build_count += 1;
        } else if (std.mem.startsWith(u8, fixture.name, "TestForm")) {
            try direct.append(a, fixture);
        } else {
            std.debug.print("unrecognized fixture {s}\n", .{fixture.name});
            return error.UnknownNarrativeFixture;
        }
    }
    try out.writeAll("};\n\n");

    const sign_cases = [_][]const u8{
        "TestFormRampStraightInstruction",
        "TestFormRampRightInstruction",
        "TestFormRampLeftInstruction",
        "TestFormExitRightInstruction",
        "TestFormExitLeftInstruction",
    };
    try out.writeAll("pub const signed_ramps_and_exits = [_]Case{\n");
    for (sign_cases) |name| try writeSignedCase(a, out, try fixtureByName(direct.items, name));
    try out.writeAll("};\n\n");
    try writeLengthCases(a, out, try fixtureByName(direct.items, "TestFormVerbalPostTransitionInstruction"), .post);
    try writeLengthCases(a, out, try fixtureByName(direct.items, "TestFormVerbalAlertApproachInstruction"), .approach);
    try writeLengthCases(a, out, try fixtureByName(direct.items, "TestFormVerbalMultiCue"), .multi_cue);
    if (direct.items.len != sign_cases.len + 3) return error.UnknownDirectFixture;

    try out.print("pub const pinned_narrative_count = {d};\npub const pinned_narrative_build_count = {d};\n", .{ all_count, build_count });
    try out.writeAll("pub const deferred_transit = [_][]const u8{\n");
    for (transit.items) |name| try out.print("    \"{f}\",\n", .{std.zig.fmtString(name)});
    try out.writeAll("};\n\npub const pinned_maneuver_cases = [_][]const u8{\n");
    scanner = .{ .source = maneuvers };
    while (try nextTest(a, &scanner, "Maneuversbuilder")) |fixture| {
        try out.print("    \"{f}\",\n", .{std.zig.fmtString(fixture.name)});
    }
    try out.writeAll("};\n");
    try writeSignCases(a, out, sign_tests);
    try writeDictionaryCases(a, out, dictionary_tests);
    return result.toOwnedSlice();
}

fn fixtureByName(fixtures: []const Test, name: []const u8) !Test {
    for (fixtures) |fixture| {
        if (eq(fixture.name, name)) return fixture;
    }
    return error.MissingFixture;
}

fn writeBuildCase(a: Allocator, out: *Writer, source: []const u8, fixture: Test) !void {
    var setup: cpp.Scanner = .{ .source = fixture.body };
    const populate = (try cpp.nextCall(&setup, "Populate", true)) orelse return error.MissingManeuverSetup;
    const body = try cpp.definition(source, populate.name);
    const setup_arguments = try cpp.arguments(a, populate.arguments);
    if (setup_arguments.len < 3 or setup_arguments.len > 4) return error.InvalidManeuverSetup;
    const drive_on_right = if (setup_arguments.len == 4 and !eq(setup_arguments[3], "roundabout_exit_count"))
        try boolean(setup_arguments[3])
    else
        true;
    const country = try cpp.stringValue(a, fixture.body, "country_code");
    const state = try cpp.stringValue(a, fixture.body, "state_code");
    const style: []const u8 = if (!eq(country, "US")) "generic" else if (eq(state, "CO")) "colorado" else if (eq(state, "TX")) "texas" else "us";
    const language = try cpp.strings(a, (try cpp.callArguments(a, fixture.body, "set_language"))[0]);
    const units = cpp.tail((try cpp.callArguments(a, fixture.body, "set_units"))[0], "::");
    try out.print(".{{ .name = \"{f}\",\n", .{std.zig.fmtString(fixture.name)});
    if (std.mem.startsWith(u8, fixture.name, "DISABLED_")) try out.writeAll(".upstream_disabled = true,\n");
    if (!eq(language, "en-US")) try writeStringField(out, "language", language);
    if (!eq(units, "miles")) try out.print(".units = .{s},\n", .{units});
    const name = try optionalCall(a, fixture.body, "set_name");
    const street = try optionalCall(a, fixture.body, "set_street");
    if (name != null or street != null) {
        try out.writeAll(".destination = .{ ");
        if (name) |value| try writeStringField(out, "name", try cpp.strings(a, value));
        if (street) |value| try writeStringField(out, "street", try cpp.strings(a, value));
        try out.writeAll("},\n");
    }
    try out.writeAll(".steps = &.{\n");
    var expected: std.ArrayList([][]const u8) = .empty;
    var expectation: cpp.Scanner = .{ .source = fixture.body };
    while (try cpp.nextCall(&expectation, "SetExpected", true)) |call| {
        if (!eq(call.name, "SetExpectedManeuverInstructions") and !eq(call.name, "SetExpectedPreviousManeuverInstructions"))
            return error.UnknownExpectation;
        const values = try cpp.arguments(a, call.arguments);
        if (values.len < 6) return error.MissingExpectedCue;
        if (eq(call.name, "SetExpectedPreviousManeuverInstructions"))
            try expected.insert(a, 0, values[1..6])
        else
            try expected.append(a, values[1..6]);
    }
    var populator: cpp.Scanner = .{ .source = body };
    var found: usize = 0;
    while (try cpp.nextCall(&populator, "PopulateManeuver", false)) |call| {
        if (found == expected.items.len) return error.UnexpectedManeuver;
        const values = try cpp.arguments(a, call.arguments);
        const outputs = expected.items[found];
        found += 1;
        if (values.len > 34 and eq(values[34], "roundabout_exit_count")) {
            // The upstream TEST parameterizes this fixture over ten ordinals.
            const names = try ordinals(a, fixture.body);
            for (names, 1..) |ordinal, number| {
                try out.writeAll(".{ .maneuver = ");
                try writeManeuver(a, out, values, body, style, drive_on_right, number);
                try writeExpectation(a, out, outputs, ordinal);
            }
        } else {
            try out.writeAll(".{ .maneuver = ");
            try writeManeuver(a, out, values, body, style, drive_on_right, null);
            try writeExpectation(a, out, outputs, null);
        }
    }
    if (found == 0 or found != expected.items.len) return error.UnmatchedManeuverExpectations;
    try out.writeAll("}, },\n");
}

fn ordinals(a: Allocator, body: []const u8) ![][]const u8 {
    var scanner: cpp.Scanner = .{ .source = body };
    while (try scanner.next()) |token| {
        if (!token.is("kExpectedOrdinalValues")) continue;
        const equals = (try scanner.next()) orelse return error.MissingOrdinals;
        if (!equals.is("=")) return error.MissingOrdinals;
        const opening = (try scanner.next()) orelse return error.MissingOrdinals;
        if (!opening.is("{")) return error.MissingOrdinals;
        const group = try scanner.group(opening);
        const args = try cpp.arguments(a, group);
        if (args.len != 10) return error.UnexpectedOrdinalCount;
        for (args) |*arg| arg.* = try cpp.strings(a, arg.*);
        return args;
    }
    return error.MissingOrdinals;
}

fn writeExpectation(a: Allocator, out: *Writer, values: [][]const u8, ordinal: ?[]const u8) !void {
    const keys = [_][]const u8{ "text", "succinct", "alert", "pre", "post" };
    for (values, keys, 0..) |expression, key, index| {
        var value = try cpp.strings(a, expression);
        if (ordinal) |word| {
            if (std.mem.indexOf(u8, expression, "ordinal_value") != null) {
                const gap = std.mem.indexOf(u8, value, "  ") orelse return error.MissingOrdinalPlaceholder;
                value = try std.fmt.allocPrint(a, "{s} {s} {s}", .{ value[0..gap], word, value[gap + 2 ..] });
            }
        }
        if (index == 0) {
            try writeStringField(out, key, value);
            try out.writeAll(".speech = .{ ");
        } else if (value.len != 0) {
            try writeStringField(out, key, value);
        }
    }
    try out.writeAll("}, },\n");
}

fn writeManeuver(a: Allocator, out: *Writer, args: [][]const u8, body: []const u8, style: []const u8, drive_on_right: bool, ordinal: ?usize) !void {
    if (args.len < 32 or args.len > 50) return error.InvalidManeuverArguments;
    const kind = cpp.tail(args[3], "_");
    try out.print(".{{ .type = .{s}, ", .{kind});
    if (!eq(style, "generic")) try out.print(".verbal_style = .{s}, ", .{style});
    try out.print(".length_km = {s}, ", .{floatLiteral(args[8])});
    if (args.len > 46) try out.print(".basic_time = {s}, ", .{floatLiteral(args[46])});
    if (args.len > 49 and try boolean(args[49])) try out.writeAll(".has_long_street_name = true, ");
    for ([_][]const u8{ "street_names", "begin_street_names", "cross_street_names" }, args[4..7]) |name, expression| {
        if (eq(expression, "{}")) continue;
        try out.print(".{s} = ", .{name});
        try writeNames(a, out, expression);
        try out.writeAll(", ");
    }
    try writeRelative(out, args[11], false);
    if (eq(kind, "kStart") or eq(kind, "kStartLeft") or eq(kind, "kStartRight") or
        eq(kind, "kFerryExit") or eq(kind, "kPostTransitConnectionDestination"))
    {
        try out.print(".begin_cardinal_direction = .{s}, ", .{cpp.tail(args[12], "_")});
    }
    if (try boolean(args[19])) try out.writeAll(".ramp = true, ");
    if (try boolean(args[23])) try out.writeAll(".roundabout = true, ");
    try writeSignFields(a, out, args[28..32]);
    if (ordinal) |value| {
        try out.print(".roundabout_exit_count = {d}, ", .{value});
    } else if (args.len > 34 and !eq(args[34], "0") and !eq(args[34], "false")) {
        try out.print(".roundabout_exit_count = {s}, ", .{args[34]});
    }
    for ([_][]const u8{ "walkway", "cycleway", "mtb_trail" }, 43..) |trail, i| {
        if (args.len > i and try boolean(args[i])) try out.print(".trail_type = .unnamed_{s}, ", .{trail});
    }
    if (args.len > 48) {
        const right = if (eq(args[48], "drive_on_right")) drive_on_right else try boolean(args[48]);
        if (!right) try out.writeAll(".drive_on_right = false, ");
    }
    for ([_][]const u8{ "travel_mode", "pedestrian_crossing", "to_stay_on", "include_verbal_pre_transition_length" }) |field| {
        if (try setter(a, body, args[0], field)) |value| {
            if (eq(field, "travel_mode")) {
                try out.print(".travel_mode = .{s}, ", .{cpp.tail(value, "::")});
            } else {
                try out.print(".{s} = {}, ", .{ field, try boolean(value) });
            }
        }
    }
    try out.writeAll("}, ");
}

fn optionalCall(a: Allocator, body: []const u8, name: []const u8) !?[]const u8 {
    var scanner: cpp.Scanner = .{ .source = body };
    const call = (try cpp.nextCall(&scanner, name, false)) orelse return null;
    const args = try cpp.arguments(a, call.arguments);
    if (args.len != 1) return error.UnexpectedSetterArguments;
    return args[0];
}

fn setter(a: Allocator, source: []const u8, variable: []const u8, field: []const u8) !?[]const u8 {
    var scanner: cpp.Scanner = .{ .source = source };
    while (try scanner.next()) |token| {
        if (!token.is(variable)) continue;
        var lookahead = scanner;
        const dot = (try lookahead.next()) orelse break;
        if (!dot.is(".")) continue;
        const method = (try lookahead.next()) orelse break;
        if (!std.mem.startsWith(u8, method.text, "set_") or !eq(field, method.text[4..])) continue;
        const opening = (try lookahead.next()) orelse return error.MissingSetterArguments;
        if (!opening.is("(")) return error.MissingSetterArguments;
        const args = try cpp.arguments(a, try lookahead.group(opening));
        if (args.len != 1) return error.UnexpectedSetterArguments;
        return args[0];
    }
    return null;
}

fn list(a: Allocator, expression: []const u8) ![][]const u8 {
    var scanner: cpp.Scanner = .{ .source = expression };
    const opening = (try scanner.next()) orelse return error.MissingList;
    if (!opening.is("{")) return error.InvalidList;
    const body = try scanner.group(opening);
    if (try scanner.next() != null) return error.UnexpectedListSuffix;
    return cpp.arguments(a, body);
}

fn writeNames(a: Allocator, out: *Writer, expression: []const u8) !void {
    try out.writeAll("&.{ ");
    for (try list(a, expression)) |item| {
        const fields = try list(a, item);
        if (fields.len != 2) return error.InvalidNameFields;
        try out.print(".{{ .value = \"{f}\", .is_route_number = {} }}, ", .{
            std.zig.fmtString(try cpp.strings(a, fields[0])),
            try boolean(fields[1]),
        });
    }
    try out.writeByte('}');
}

fn writeSignFields(a: Allocator, out: *Writer, fields: [][]const u8) !void {
    const names = [_][]const u8{ "exit_numbers", "exit_onto_streets", "exit_toward_locations", "exit_names" };
    var started = false;
    for (fields, names) |expr, name| {
        const entries = try list(a, expr);
        if (entries.len == 0) continue;
        if (!started) {
            try out.writeAll(".signs = .{ ");
            started = true;
        }
        try out.print(".{s} = ", .{name});
        try writeSignEntries(a, out, entries, "");
        try out.writeAll(", ");
    }
    if (started) try out.writeAll("}, ");
}

fn writeRelative(out: *Writer, expression: []const u8, include_none: bool) !void {
    const relative = cpp.tail(expression, "::");
    if (relative.len < 2 or std.ascii.toLower(relative[0]) != 'k') return error.InvalidRelativeDirection;
    if (!include_none and eq(relative, "kNone")) return;
    try out.writeAll(".begin_relative_direction = .");
    for (relative[1..], 0..) |byte, index| {
        if (index != 0 and std.ascii.isUpper(byte)) try out.writeByte('_');
        try out.writeByte(std.ascii.toLower(byte));
    }
    try out.writeAll(", ");
}

fn writeSignedCase(a: Allocator, out: *Writer, fixture: Test) !void {
    const function = try std.fmt.allocPrint(a, "Try{s}", .{fixture.name[4..]});
    try out.print(".{{ .name = \"{f}\", .steps = &.{{\n", .{std.zig.fmtString(fixture.name)});
    var scanner: cpp.Scanner = .{ .source = fixture.body };
    while (try cpp.nextCall(&scanner, function, false)) |call| {
        const emit = try cpp.arguments(a, call.arguments);
        if (emit.len != 3) return error.InvalidSignFixture;
        const setup = try cpp.callArguments(a, emit[1], "CreateSignManeuver");
        if (setup.len != 7) return error.InvalidSignFixture;
        try out.print(".{{ .maneuver = .{{ .type = .{s}, ", .{cpp.tail(setup[0], "_")});
        try writeRelative(out, setup[1], true);
        if (!(try boolean(setup[2]))) try out.writeAll(".drive_on_right = false, ");
        try writeSignFields(a, out, setup[3..]);
        try out.writeAll("}, ");
        try writeStringField(out, "text", try cpp.strings(a, emit[2]));
        try out.writeAll("},\n");
    }
    try out.writeAll("}, },\n");
}

const LengthTest = enum { post, approach, multi_cue };

fn writeLengthCases(a: Allocator, out: *Writer, fixture: Test, kind: LengthTest) !void {
    const fields: []const u8 = switch (kind) {
        .post => "maneuver: Maneuver, include_street_names: bool",
        .approach => "distance: f32, cue: []const u8",
        .multi_cue => "maneuver: Maneuver, first: []const u8, next: []const u8",
    };
    try out.print("pub const {s} = [_]struct {{ units: request.Units, {s}, expected: []const u8 }}{{\n", .{ @tagName(kind), fields });
    const function = try std.fmt.allocPrint(a, "Try{s}", .{fixture.name[4..]});
    var scanner: cpp.Scanner = .{ .source = fixture.body };
    while (try cpp.nextCall(&scanner, function, false)) |call| {
        const args = try cpp.arguments(a, call.arguments);
        if (args.len != 4) return error.InvalidLengthFixture;
        const units: []const u8 = if (eq(args[0], "nbt_mi")) "miles" else if (eq(args[0], "nbt_km")) "kilometers" else return error.UnknownFixtureUnits;
        try out.print(".{{ .units = .{s}, ", .{units});
        switch (kind) {
            .post => {
                const setup = try cpp.callArguments(a, args[1], "CreateVerbalPostManeuver");
                if (setup.len < 2 or setup.len > 3) return error.InvalidLengthFixture;
                try out.writeAll(".maneuver = .{ .street_names = ");
                try writeNames(a, out, setup[0]);
                try out.writeAll(", ");
                try writeFloatField(out, "length_km", setup[1]);
                if (setup.len == 3) try out.print(".type = .{s}, ", .{cpp.tail(setup[2], "_")});
                try out.print("}}, .include_street_names = {}, ", .{try boolean(args[2])});
            },
            .approach => {
                try writeFloatField(out, "distance", args[1]);
                try writeStringField(out, "cue", try cpp.strings(a, args[2]));
            },
            .multi_cue => {
                const first = try cpp.callArguments(a, args[1], "CreateVerbalMultiCueCurrentManeuver");
                const next = try cpp.callArguments(a, args[2], "CreateVerbalMultiCueNextManeuver");
                if ((first.len != 1 and first.len != 3) or next.len != 1) return error.InvalidLengthFixture;
                try out.writeAll(".maneuver = .{ ");
                if (first.len > 1) {
                    try out.print(".distant_verbal_multi_cue = {}, ", .{try boolean(first[1])});
                    try writeFloatField(out, "length_km", first[2]);
                }
                try out.writeAll("}, ");
                try writeStringField(out, "first", try cpp.strings(a, first[0]));
                try writeStringField(out, "next", try cpp.strings(a, next[0]));
            },
        }
        try writeStringField(out, "expected", try cpp.strings(a, args[3]));
        try out.writeAll("},\n");
    }
    try out.writeAll("};\n\n");
}

fn boolean(raw: []const u8) !bool {
    if (eq(raw, "true") or eq(raw, "1")) return true;
    if (eq(raw, "false") or eq(raw, "0")) return false;
    return error.InvalidBooleanLiteral;
}

fn floatLiteral(raw: []const u8) []const u8 {
    if (raw.len > 1 and (raw[raw.len - 1] == 'f' or raw[raw.len - 1] == 'F')) return raw[0 .. raw.len - 1];
    return raw;
}

fn writeFloatField(out: *Writer, name: []const u8, raw: []const u8) !void {
    const value = floatLiteral(raw);
    try out.print(".{s} = {s}{s}, ", .{ name, value, if (std.mem.endsWith(u8, value, ".")) "0" else "" });
}

fn writeStringField(out: *Writer, name: []const u8, value: []const u8) !void {
    try out.print(".{s} = \"{f}\", ", .{ name, std.zig.fmtString(value) });
}

fn eq(a: []const u8, b: []const u8) bool {
    return std.mem.eql(u8, a, b);
}

const SignPart = enum {
    exit_numbers,
    exit_onto_streets,
    exit_toward_locations,
    exit_names,
    guide_onto_streets,
    guide_toward_locations,
    junction_names,
    guide,
    trim,
};

const sign_parts = std.StaticStringMap(SignPart).initComptime(.{
    .{ "GetExitNumberSigns", .exit_numbers },
    .{ "GetExitBranchSigns", .exit_onto_streets },
    .{ "GetExitTowardSigns", .exit_toward_locations },
    .{ "GetExitNameSigns", .exit_names },
    .{ "GetGuideBranchSigns", .guide_onto_streets },
    .{ "GetGuideTowardSigns", .guide_toward_locations },
    .{ "GetJunctionNameSigns", .junction_names },
    .{ "GetGuideSigns", .guide },
    .{ "PopulateSigns", .trim },
});

fn writeSignCases(a: Allocator, out: *Writer, source: []const u8) !void {
    try out.writeAll(
        \\
        \\// Ported from test/signs.cc (Valhalla 3.9.3).
        \\pub const SignCase = struct {
        \\    name: []const u8,
        \\    part: enum {
        \\        exit_numbers, exit_onto_streets, exit_toward_locations, exit_names,
        \\        guide_onto_streets, guide_toward_locations, junction_names, guide, trim,
        \\    },
        \\    sign: trip.Sign,
        \\    trials: []const SignTrial,
        \\};
        \\pub const SignTrial = struct {
        \\    limit: usize,
        \\    consecutive: bool,
        \\    expected: union(enum) { text: []const u8, elements: []const trip.SignElement },
        \\};
        \\pub const sign_cases = [_]SignCase{
        \\
    );
    var scanner: cpp.Scanner = .{ .source = source };
    while (try nextTest(a, &scanner, "Signs")) |fixture| {
        writeSignCase(a, out, fixture) catch |err| {
            std.debug.print("{s}: {s}\n", .{ fixture.name, @errorName(err) });
            return err;
        };
    }
    try out.writeAll("};\n");
}

fn writeSignCase(a: Allocator, out: *Writer, fixture: Test) !void {
    var setup: cpp.Scanner = .{ .source = fixture.body };
    const call = (if (eq(fixture.name, "TestTrimSigns"))
        try cpp.nextCall(&setup, "PopulateSigns", false)
    else
        try cpp.nextCall(&setup, "Get", true)) orelse return error.MissingSignFixtureSetup;
    const part = sign_parts.get(call.name) orelse return error.UnknownSignFixtureSetup;
    const inputs = try cpp.arguments(a, call.arguments);
    const first_field: []const u8 = switch (part) {
        .guide => "guide_onto_streets",
        .trim => "exit_onto_streets",
        else => @tagName(part),
    };
    try out.print(".{{ .name = \"{f}\", .part = .{s}, .sign = .{{ .{s} = ", .{ std.zig.fmtString(fixture.name), @tagName(part), first_field });
    try writeSignEntries(a, out, try list(a, inputs[0]), fixture.body);
    if (part == .guide) {
        try out.writeAll(", .guide_toward_locations = ");
        try writeSignEntries(a, out, try list(a, inputs[1]), fixture.body);
    }
    try out.writeAll(" }, .trials = &.{\n");

    var trials: cpp.Scanner = .{ .source = fixture.body };
    while (try cpp.nextCall(&trials, "Try", true)) |trial| {
        const args = try cpp.arguments(a, trial.arguments);
        const expected = if (part == .trim) blk: {
            if (args.len != 2) return error.InvalidSignTrial;
            const trim = try cpp.callArguments(a, args[0], "TrimSigns");
            if (trim.len != 1 and trim.len != 3) return error.InvalidSignTrial;
            try writeSignTrialStart(out, if (trim.len == 1) "0" else trim[1], if (trim.len == 1) false else try boolean(trim[2]));
            break :blk args[1];
        } else blk: {
            if (args.len != 4) return error.InvalidSignTrial;
            try writeSignTrialStart(out, args[1], try boolean(args[2]));
            break :blk args[3];
        };
        if (part == .trim or eq(trial.name, "TryGetGuideSigns")) {
            try out.writeAll(".elements = ");
            try writeSignEntries(a, out, try list(a, expected), fixture.body);
        } else {
            try out.print(".text = \"{f}\"", .{std.zig.fmtString(try cpp.strings(a, expected))});
        }
        try out.writeAll(" } },\n");
    }
    try out.writeAll("}, },\n");
}

fn writeSignTrialStart(out: *Writer, limit: []const u8, consecutive: bool) !void {
    try out.print(".{{ .limit = {s}, .consecutive = {}, .expected = .{{ ", .{ limit, consecutive });
}

fn writeSignEntries(a: Allocator, out: *Writer, entries: [][]const u8, bindings: []const u8) !void {
    try out.writeAll("&.{ ");
    for (entries) |entry| {
        const item = if (std.mem.indexOf(u8, entry, "make_tuple") != null)
            try cpp.callArguments(a, entry, "make_tuple")
        else
            try boundTuple(a, bindings, entry);
        if (item.len != 3) return error.InvalidSignFields;
        try out.print(".{{ .text = \"{f}\", ", .{std.zig.fmtString(try cpp.strings(a, item[0]))});
        if (try boolean(item[1])) try out.writeAll(".is_route_number = true, ");
        if (!eq(item[2], "0")) try out.print(".consecutive_count = {s}, ", .{item[2]});
        try out.writeAll("}, ");
    }
    try out.writeByte('}');
}

fn boundTuple(a: Allocator, body: []const u8, name: []const u8) ![][]const u8 {
    var scanner: cpp.Scanner = .{ .source = body };
    while (try scanner.next()) |token| {
        if (!token.is(name)) continue;
        const equals = (try scanner.next()) orelse break;
        if (!equals.is("=")) continue;
        return cpp.callArguments(a, body[scanner.cursor..], "make_tuple");
    }
    return error.MissingSignBinding;
}

fn writeDictionaryCases(a: Allocator, out: *Writer, source: []const u8) !void {
    try out.writeAll(
        \\
        \\// Ported from test/narrative_dictionary.cc (Valhalla 3.9.3).
        \\pub fn compareDictionary(dict: anytype, snapshot: anytype) !void {
        \\
    );
    var scanner: cpp.Scanner = .{ .source = source };
    var count: usize = 0;
    while (try nextTest(a, &scanner, "NarrativeDictionary")) |fixture| {
        writeDictionaryCase(a, out, source, fixture) catch |err| {
            std.debug.print("{s}: {s}\n", .{ fixture.name, @errorName(err) });
            return err;
        };
        count += 1;
    }
    try out.print("}}\n\npub const pinned_dictionary_count = {d};\n", .{count});
}

fn writeDictionaryCase(a: Allocator, out: *Writer, source: []const u8, fixture: Test) !void {
    const locale = try cpp.callArguments(a, fixture.body, "GetNarrativeDictionary");
    if (locale.len != 1 or !eq(try cpp.strings(a, locale[0]), "en-US")) return error.UnsupportedDictionaryFixture;
    try out.print("{{\nconst name = \"{f}\";\n", .{std.zig.fmtString(fixture.name)});
    var checks: cpp.Scanner = .{ .source = fixture.body };
    while (try cpp.nextCall(&checks, "validate", false)) |call| {
        const args = try cpp.arguments(a, call.arguments);
        if (args.len != 2) return error.InvalidDictionaryFixture;
        const target = if (std.mem.startsWith(u8, args[0], "dictionary->"))
            args[0]
        else
            try assignedExpression(fixture.body, args[0]);
        const expected = if (std.mem.startsWith(u8, args[1], "kExpected"))
            try assignedExpression(source, args[1])
        else
            args[1];
        if (!std.mem.startsWith(u8, target, "dictionary->")) return error.InvalidDictionaryTarget;
        try writeDictionaryCheck(a, out, target["dictionary->".len..], expected);
    }
    try out.writeAll("}\n");
}

fn assignedExpression(source: []const u8, name: []const u8) ![]const u8 {
    var scanner: cpp.Scanner = .{ .source = source };
    while (try scanner.next()) |token| {
        if (!token.is(name)) continue;
        var lookahead = scanner;
        const equals = (try lookahead.next()) orelse break;
        if (!equals.is("=")) continue;
        const start = (try lookahead.next()) orelse return error.MissingFixtureValue;
        if (start.is("{")) {
            _ = try lookahead.group(start);
            return source[start.start..lookahead.cursor];
        }
        while (try lookahead.next()) |part| {
            if (part.is(";")) return std.mem.trim(u8, source[start.start..part.start], " \r\n\t");
        }
        return error.MissingFixtureValue;
    }
    return error.MissingFixtureValue;
}

fn writeDictionaryCheck(a: Allocator, out: *Writer, target: []const u8, expected: []const u8) !void {
    if (std.mem.indexOf(u8, target, ".at(")) |start| {
        const args = try cpp.callArguments(a, target[start..], "at");
        if (args.len != 1) return error.InvalidDictionaryIndex;
        const key = try std.fmt.parseInt(u8, try cpp.strings(a, args[0]), 10);
        try out.print("try snapshot.match(name, \"{f}\", dict.{s}.get({d}) orelse return error.MissingPhrase);\n", .{
            std.zig.fmtString(try cpp.strings(a, expected)), target[0..start], key,
        });
        return;
    }
    if (!std.mem.startsWith(u8, expected, "{")) {
        try out.print("try snapshot.match(name, \"{f}\", dict.{s});\n", .{ std.zig.fmtString(try cpp.strings(a, expected)), target });
        return;
    }
    const entries = try list(a, expected);
    const phrases = std.mem.endsWith(u8, target, ".phrases");
    const plural = std.mem.endsWith(u8, target, ".transit_stop_count_labels");
    if (phrases or plural) {
        for (entries) |entry| {
            const pair = try list(a, entry);
            if (pair.len != 2) return error.InvalidDictionaryEntry;
            const key = try cpp.strings(a, pair[0]);
            const value = std.zig.fmtString(try cpp.strings(a, pair[1]));
            if (plural) {
                try out.print("try snapshot.match(name, \"{f}\", dict.{s}.get(.{s}) orelse return error.MissingLabel);\n", .{ value, target, key });
            } else {
                try out.print("try snapshot.match(name, \"{f}\", dict.{s}.get({d}) orelse return error.MissingPhrase);\n", .{ value, target, try std.fmt.parseInt(u8, key, 10) });
            }
        }
    } else {
        try out.print("try snapshot.count({d}, dict.{s}.len);\n", .{ entries.len, target });
        for (entries, 0..) |entry, index| {
            try out.print("try snapshot.match(name, \"{f}\", dict.{s}[{d}]);\n", .{ std.zig.fmtString(try cpp.strings(a, entry)), target, index });
        }
    }
}
